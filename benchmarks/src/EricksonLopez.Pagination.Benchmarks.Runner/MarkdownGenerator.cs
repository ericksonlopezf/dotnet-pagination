namespace EricksonLopez.Pagination.Benchmarks.Runner;

public static class MarkdownGenerator
{
    public static void Generate()
    {
        var artifactsDir = Path.Combine(Directory.GetCurrentDirectory(), "BenchmarkDotNet.Artifacts", "results");
        if (!Directory.Exists(artifactsDir))
        {
            Console.WriteLine("Artifacts directory not found, skipping doc generation.");
            return;
        }

        var docsDir = Path.GetFullPath(Path.Combine(Directory.GetCurrentDirectory(), "..", "..", "..", "docs"));
        Directory.CreateDirectory(docsDir);

        var benchmarkMdPath = Path.Combine(docsDir, "benchmark.md");
        using var writer = new StreamWriter(benchmarkMdPath);

        WriteEnvironmentHeader(writer);

        var mdFiles = Directory.GetFiles(artifactsDir, "*-report-github.md");
        if (mdFiles.Length == 0) return;

        // Extract overall winners across all benchmarks to put at the top
        var winners = ExtractWinners(mdFiles);
        WriteExecutiveSummary(writer, winners);

        foreach (var mdFile in mdFiles)
        {
            var titleName = GetTitleName(mdFile);
            writer.WriteLine($"## {titleName}");
            writer.WriteLine();

            ProcessBenchmarkFile(writer, mdFile, titleName);
            WriteConclusions(writer, titleName);
        }

        Console.WriteLine($"Documentation generated at {benchmarkMdPath}");
    }

    private static void WriteEnvironmentHeader(StreamWriter writer)
    {
        writer.WriteLine("# 📊 Benchmark Results (Multi-Engine)");
        writer.WriteLine("This document is automatically generated by `BenchmarkRunner`.");
        writer.WriteLine();
        writer.WriteLine("## 🖥️ Environment & Setup");
        writer.WriteLine("- **Dataset**: 1,000,000 records seeded in each database engine.");
        writer.WriteLine("- **Indexes**: Optimal indexes applied (e.g., `IX_Products_Price_CreatedAt` for Keyset/Sort).");
        writer.WriteLine("- **EF Core**: All queries are executed using `AsNoTracking()` to isolate translation and execution speed without Change Tracker overhead.");
        writer.WriteLine("- **Isolation**: No ambient transactions are used during reading to prevent lock contention.");
        writer.WriteLine("- **Framework**: .NET 10.0 with Release configuration.");
        writer.WriteLine();
        writer.WriteLine("## 🏆 Legend");
        writer.WriteLine("- **🚀 EricksonLopez**: The reference implementation under test (Our Library).");
        writer.WriteLine("- **🔧 RawSqlOffset / RawSqlKeyset**: The raw Entity Framework Core SQL baseline.");
        writer.WriteLine("- **✅ Best 🥇**: The fastest provider for a given parameter block.");
        writer.WriteLine("- **❌ Worst**: The slowest provider for a given parameter block.");
        writer.WriteLine();
    }

    private static string GetTitleName(string mdFile)
    {
        var titleName = Path.GetFileNameWithoutExtension(mdFile).Replace("-report-github", "");
        if (titleName.Contains('.'))
        {
            titleName = titleName.Substring(titleName.LastIndexOf('.') + 1);
        }
        return Regex.Replace(titleName, "([a-z])([A-Z])", "$1 $2");
    }

    private static Dictionary<string, string> ExtractWinners(string[] mdFiles)
    {
        var scores = new Dictionary<string, Dictionary<string, int>>(); // Engine -> Provider -> Wins

        foreach (var mdFile in mdFiles)
        {
            var blocks = ParseMarkdownTableBlocks(mdFile);
            foreach (var block in blocks)
            {
                var fastest = block.Rows.Where(x => x.MeanUs > 0).OrderBy(x => x.MeanUs).FirstOrDefault();
                if (fastest != null)
                {
                    if (!scores.ContainsKey(fastest.Engine))
                        scores[fastest.Engine] = new Dictionary<string, int>();

                    if (!scores[fastest.Engine].ContainsKey(fastest.Provider))
                        scores[fastest.Engine][fastest.Provider] = 0;

                    scores[fastest.Engine][fastest.Provider]++;
                }
            }
        }

        var winners = new Dictionary<string, string>();
        foreach (var engine in scores.Keys)
        {
            var topProvider = scores[engine].OrderByDescending(x => x.Value).First().Key;
            winners[engine] = topProvider;
        }

        return winners;
    }

    private static void WriteExecutiveSummary(StreamWriter writer, Dictionary<string, string> winners)
    {
        writer.WriteLine("## ⚡ Executive Summary");
        writer.WriteLine("The table below shows the overall dominant pagination provider per database engine across all benchmarks.");
        writer.WriteLine();
        writer.WriteLine("| Database Engine | Overall Winner |");
        writer.WriteLine("|----------------|----------------|");
        foreach (var engine in winners.Keys.OrderBy(x => x))
        {
            var displayWinner = winners[engine];
            // Format winner
            if (displayWinner == "EricksonLopez") displayWinner = "🚀 **EricksonLopez**";
            else if (displayWinner.StartsWith("RawSql")) displayWinner = $"🔧 {displayWinner}";
            
            writer.WriteLine($"| {engine} | {displayWinner} |");
        }
        writer.WriteLine();
    }

    private static void ProcessBenchmarkFile(StreamWriter writer, string mdFile, string titleName)
    {
        var blocks = ParseMarkdownTableBlocks(mdFile);
        if (!blocks.Any())
        {
            // Just write original if we fail to parse
            writer.WriteLine(File.ReadAllText(mdFile));
            return;
        }
        
        // Write the BenchmarkDotNet Environment Header (first few lines)
        var lines = File.ReadAllLines(mdFile);
        foreach(var line in lines)
        {
            if (line.StartsWith('|')) break;
            writer.WriteLine(line);
        }

        // Draw Mermaid Chart
        WriteMermaidChart(writer, blocks, titleName);

        // Reconstruct Table
        writer.WriteLine(blocks[0].HeaderLine);
        writer.WriteLine(blocks[0].SeparatorLine);

        for (int i = 0; i < blocks.Count; i++)
        {
            var block = blocks[i];
            var validRows = block.Rows.Where(x => x.MeanUs > 0).ToList();
            var minMean = validRows.Any() ? validRows.Min(x => x.MeanUs) : 0;
            var maxMean = validRows.Any() ? validRows.Max(x => x.MeanUs) : 0;

            foreach (var row in block.Rows)
            {
                var rowLine = row.OriginalLine;

                // Add Indicators
                if (row.MeanUs > 0 && validRows.Count > 1)
                {
                    if (Math.Abs(row.MeanUs - minMean) < 0.0001)
                    {
                        rowLine = rowLine.Replace(row.Provider, $"{row.Provider} ✅ Best 🥇");
                    }
                    else if (Math.Abs(row.MeanUs - maxMean) < 0.0001)
                    {
                        rowLine = rowLine.Replace(row.Provider, $"{row.Provider} ❌ Worst");
                    }
                }

                // Format Known Providers
                rowLine = Regex.Replace(rowLine, @"\|\s*EricksonLopez(?:\s*(?:✅ Best 🥇|❌ Worst))?\s*(?=\|)", match => match.Value.Replace("EricksonLopez", "🚀 **EricksonLopez**"));
                rowLine = Regex.Replace(rowLine, @"\|\s*RawSqlOffset(?:\s*(?:✅ Best 🥇|❌ Worst))?\s*(?=\|)", match => match.Value.Replace("RawSqlOffset", "🔧 RawSqlOffset"));
                rowLine = Regex.Replace(rowLine, @"\|\s*RawSqlKeyset(?:\s*(?:✅ Best 🥇|❌ Worst))?\s*(?=\|)", match => match.Value.Replace("RawSqlKeyset", "🔧 RawSqlKeyset"));

                writer.WriteLine(rowLine);
            }
            
            // Empty row block separator
            writer.WriteLine("| | | | | | | | | | | | | | | |");
        }
    }

    private static void WriteMermaidChart(StreamWriter writer, List<TableBlock> blocks, string titleName)
    {
        writer.WriteLine("### 📈 Performance Trend (PageSize 10, Page 1)");
        writer.WriteLine("```mermaid");
        writer.WriteLine("xychart-beta");
        writer.WriteLine($"    title \"{titleName} (Latency in us)\"");
        
        var firstPageBlock = blocks.Find(x => x.PageSize == "10" && x.PageNumber == "1");
        if (firstPageBlock != null)
        {
            var engines = firstPageBlock.Rows.Select(x => x.Engine).Distinct().ToList();
            writer.WriteLine($"    x-axis [{string.Join(", ", engines.Select(e => $"\"{e}\""))}]");
            writer.WriteLine("    y-axis \"Latency (us)\"");

            var providers = firstPageBlock.Rows.Select(x => x.Provider).Distinct().ToList();
            foreach (var provider in providers)
            {
                var values = new List<string>();
                foreach (var engine in engines)
                {
                    var row = firstPageBlock.Rows.Find(x => x.Engine == engine && x.Provider == provider);
                    values.Add(row != null && row.MeanUs > 0 ? row.MeanUs.ToString("F0", CultureInfo.InvariantCulture) : "0");
                }
                writer.WriteLine($"    bar \"{provider}\" [{string.Join(", ", values)}]");
            }
        }
        
        writer.WriteLine("```");
        writer.WriteLine();
    }

    private static void WriteConclusions(StreamWriter writer, string titleName)
    {
        writer.WriteLine("### 💡 Insights & Conclusions");
        writer.WriteLine("> [!NOTE]");
        
        if (titleName.Contains("Offset Pagination"))
        {
            writer.WriteLine("> **Offset Pagination**: EricksonLopez generally matches or beats Raw SQL. However, notice how latency increases linearly with the `PageNumber` (Deep Pagination). This is a structural limitation of Offset-based pagination in relational databases (the database must scan and skip N rows before reading the target rows).");
        }
        else if (titleName.Contains("Keyset Pagination"))
        {
            writer.WriteLine("> **Keyset Pagination**: Observe how Keyset completely eliminates the deep-pagination latency penalty. Even at Page 10,000, the latency remains flat. EricksonLopez provides native Keyset extension methods that map to EF Core optimally.");
        }
        else if (titleName.Contains("Filter Pagination"))
        {
            writer.WriteLine("> **Filter Pagination**: Applying dynamic `Where` clauses adds complexity. EricksonLopez is highly optimized for this, generating lean expression trees. In some deep pagination scenarios (e.g. MySQL at Page 10,000), Raw SQL might slightly edge out due to the raw driver bypassing EF Core translation completely.");
        }
        else if (titleName.Contains("Total Count Pagination"))
        {
            writer.WriteLine("> **Total Count Pagination**: Executing a `COUNT(*)` prior to fetching the page doubles the latency, as it triggers two sequential trips to the database. EricksonLopez mitigates this by allowing `countTotal: true` internally while efficiently parallelizing or optimizing the query translation.");
        }
        else if (titleName.Contains("Sort Pagination"))
        {
            writer.WriteLine("> **Sort Pagination**: Dynamic multi-column sorting requires complex expression tree building. EricksonLopez caches and compiles these expressions to minimize the overhead, beating generic libraries like Sieve that rely on heavy reflection at runtime.");
        }
        else if (titleName.Contains("Projection Pagination"))
        {
            writer.WriteLine("> **Projection Pagination**: Projections `.Select(x => new DTO())` are extremely memory efficient. Notice the significant drop in Allocated Memory compared to the standard offset benchmark, as we avoid instantiating tracked entity proxies.");
        }
        else
        {
            writer.WriteLine("> Benchmark completed successfully. The framework provides minimal abstraction overhead.");
        }
        writer.WriteLine();
    }

    private sealed class TableBlock
    {
        public string HeaderLine { get; set; } = string.Empty;
        public string SeparatorLine { get; set; } = string.Empty;
        public string PageSize { get; set; } = string.Empty;
        public string PageNumber { get; set; } = string.Empty;
        public List<TableRow> Rows { get; set; } = new();
    }

    private sealed class TableRow
    {
        public string OriginalLine { get; set; } = string.Empty;
        public string Provider { get; set; } = string.Empty;
        public string Engine { get; set; } = string.Empty;
        public double MeanUs { get; set; }
    }

    private static List<TableBlock> ParseMarkdownTableBlocks(string mdFile)
    {
        var lines = File.ReadAllLines(mdFile);
        var blocks = new List<TableBlock>();
        
        TableBlock? currentBlock = null;

        string headerLine = "";
        string separatorLine = "";
        int methodIdx = -1, pageSizeIdx = -1, pageNumberIdx = -1, engineIdx = -1, meanIdx = -1;

        foreach (var line in lines)
        {
            if (!line.TrimStart().StartsWith('|')) continue;

            if (headerLine == "")
            {
                headerLine = line;
                var cols = line.Split('|').Select(x => x.Trim()).ToList();
                methodIdx = cols.IndexOf("Method");
                pageSizeIdx = cols.IndexOf("PageSize");
                pageNumberIdx = cols.IndexOf("PageNumber");
                engineIdx = cols.IndexOf("Engine");
                meanIdx = cols.IndexOf("Mean");
                continue;
            }

            if (separatorLine == "")
            {
                separatorLine = line;
                continue;
            }

            // It's a row
            if (string.IsNullOrWhiteSpace(line.Replace("|", "")))
            {
                // Empty row block separator
                if (currentBlock != null && currentBlock.Rows.Any())
                {
                    blocks.Add(currentBlock);
                    currentBlock = null;
                }
                continue;
            }

            var rowCols = line.Split('|').Select(x => x.Trim()).ToList();
            if (rowCols.Count <= meanIdx) continue;

            var method = rowCols[methodIdx].Replace("🚀 **", "").Replace("**", "").Replace("🔧 ", "").Trim();
            var pSize = pageSizeIdx >= 0 ? rowCols[pageSizeIdx] : "";
            var pNum = pageNumberIdx >= 0 ? rowCols[pageNumberIdx] : "";
            var engine = engineIdx >= 0 ? rowCols[engineIdx] : "";
            
            var meanStr = rowCols[meanIdx];
            double meanUs = 0;
            if (meanStr != "NA" && meanStr != "?")
            {
                // Remove commas and suffixes (e.g. "898.4 μs", "1,075.7 μs", "2.1 ms")
                var numStr = Regex.Replace(meanStr, @"[^\d\.]", "");
                if (double.TryParse(numStr, NumberStyles.Any, CultureInfo.InvariantCulture, out var val))
                {
                    meanUs = val;
                    if (meanStr.Contains("ms")) meanUs *= 1000;
                    if (meanStr.Contains("ns")) meanUs /= 1000;
                }
            }

            if (currentBlock == null)
            {
                currentBlock = new TableBlock 
                { 
                    HeaderLine = headerLine, 
                    SeparatorLine = separatorLine,
                    PageSize = pSize,
                    PageNumber = pNum
                };
            }

            currentBlock.Rows.Add(new TableRow
            {
                OriginalLine = line,
                Provider = method,
                Engine = engine,
                MeanUs = meanUs
            });
        }

        if (currentBlock != null && currentBlock.Rows.Any())
        {
            blocks.Add(currentBlock);
        }

        return blocks;
    }
}
