namespace EricksonLopez.Pagination.Abstractions;

/// <summary>
/// Specifies the direction in which results are sorted.
/// </summary>
public enum SortDirection
{
    /// <summary>
    /// Sorts results in ascending order, from smallest to largest.
    /// </summary>
    Ascending,
    
    /// <summary>
    /// Sorts results in descending order, from largest to smallest.
    /// </summary>
    Descending
}

